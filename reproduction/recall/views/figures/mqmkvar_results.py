
import json
from pathlib import Path
from mqmkvar_lr_sweep import load_sweep, select_best
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
fixed = json.loads((ROOT / 'records/paper_table.json').read_text())
cells = {(a['abbr'], t): c for table in fixed['tables'] for a in table['arms'] if a['abbr'] != 'euler' for t, c in a['cells'].items()}
best = select_best(load_sweep())
primary_ssd = ['R2O2-r', 'R2O2-c', 'R4O4-r', 'R4O4-c']

def mean(arm, tier=None):
    return cells[arm, tier]['mean'] if tier else best[arm][1]['mean']

def score(arm, tier=None):
    c = cells[arm, tier] if tier else best[arm][1]
    return f"${c['mean']:.1f}$ [${c['min']:.1f}$--${c['max']:.1f}$]"

def write(name, text):
    (HERE.parent / 'sections' / ('generated_mq_' + name + '.tex')).write_text('% Generated by figures/mqmkvar_results.py from the final result sources.\n' + text + '\n')
assert all((best[a][0] == '5e-4' for a in ['R1O1-r', 'R1O1-c', 'R2O2-r-nogate']))
assert min((mean(a) for a in primary_ssd)) >= 82
assert sorted(cells, key=lambda k: cells[k]['mean'] if k[1] == 'hard' else -1)[-2:] == [('HM-c25a', 'hard'), ('HM-c25d', 'hard')]
rank_gap_low = mean('R2O2-r') - mean('R1O1-c')
rank_gap_high = mean('R2O2-r') - mean('R1O1-r')

def rng(arm):
    c = best[arm][1]
    return (c['min'], c['max'])
assert rng('R2O2-c-nogate')[0] > rng('R1O1-c')[1]
assert mean('R2O2-r-nogate') < mean('R1O1-r') < mean('R2O2-r')
assert rng('HM-Adyn')[1] - rng('HM-Adyn')[0] < 2.0
write('rank_best', '\\paragraph{Routing rank.}' + '\n' + 'At each configuration’s best eligible LR, ungated R2O2-c reaches ' + score('R2O2-c-nogate') + ', against ' + score('R1O1-c') + ' for R1O1-c, with disjoint seed ranges. ' + 'For real rows, gated R2O2-r reaches ' + f"${mean('R2O2-r'):.1f}$" + ', but ungated R2O2-r, at ' + f"${mean('R2O2-r-nogate'):.1f}$" + ', falls below R1O1-r (' + f"${mean('R1O1-r'):.1f}$" + ') on average.\n' + 'The ungated rank-one HM mixture also reaches ' + score('HM-Adyn') + '. These configuration comparisons do not isolate the effect of routing rank (Figure~\\ref{fig:mqmkvar_final_points}).')
write('gates_best', 'The asymmetry persists after selecting each configuration’s best eligible LR: real gates-off reaches ' + score('R2O2-r-nogate') + ', versus ' + f"${mean('R2O2-r'):.1f}$" + ' with gates, whereas complex gates-off reaches ' + f"${mean('R2O2-c-nogate'):.1f}$" + ', versus ' + f"${mean('R2O2-c'):.1f}$" + ' for the complex default.')
dyn_mix = ['HM-Adyn', 'HM-c25a', 'HM-c25d']
base = ['M1', 'M2', 'M3']
assert all((mean(a, 'hard') > max((mean(b, 'hard') for b in base)) for a in dyn_mix))
assert all((mean(a) > max((mean(b) for b in base)) for a in dyn_mix))
best_ssd = max((mean(a) for a in primary_ssd))
gap = best_ssd - max((mean(a) for a in dyn_mix))
assert gap < 2.0
assert mean('HM-A') > max((mean(b) for b in base))
assert abs(mean('HM-c25d') - mean('HM-Adyn')) < 0.5
assert mean('HM-Ac') < mean('M1')
write('hm_results', '\\paragraph{HybridMamba.}' + '\n' + 'At the Mamba~1 budget, the three HM mixtures with dynamic rows exceed all three Mamba baselines on medium and hard. ' + 'On medium, the complex-dynamic mix has the highest mean of all configurations, ' + score('HM-c25d', 'hard') + '; on hard, the mixtures reach ' + f'${min((mean(a) for a in dyn_mix)):.1f}$--${max((mean(a) for a in dyn_mix)):.1f}$' + ', the best within ' + f'${gap:.1f}$' + ' points of the best SSD-MIMO configuration.\n' + 'The gains build up from Mamba~1’s' + ' static design. With the same static per-coordinate decay, ' + "HM's maps, two-endpoint write and head organization raise the hard mean from " + f"${mean('M1'):.1f}$ to ${mean('HM-A'):.1f}$; dynamic rows add " + f"${mean('HM-Adyn') - mean('HM-A'):.1f}$ points on hard and ${mean('HM-Adyn', 'hard') - mean('HM-A', 'hard'):.1f}$ on medium; " + 'complex dynamic rows add a further ' + f"${mean('HM-c25d', 'hard') - mean('HM-Adyn', 'hard'):.1f}$" + ' on medium and are neutral on hard. Complex rows with only static decay hurt on hard (' + f"${mean('HM-Ac'):.1f}$" + '). Each step changes several settings at once, so the steps are not isolated mechanisms.')
