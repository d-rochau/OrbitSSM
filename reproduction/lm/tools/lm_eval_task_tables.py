
from decimal import Decimal, ROUND_HALF_UP
from fractions import Fraction
from pathlib import Path
import argparse
import re
import sys
import textwrap
REPO = Path(__file__).resolve().parents[1]
RAW = 'records'
TASK = 'summary.txt'
BEGIN = '<!-- BEGIN per-task downstream tables: generated by tools/lm_eval_task_tables.py, do not edit -->'
END = '<!-- END per-task downstream tables -->'
DIRS = {'1B': ('recall6_1B', 'ssd_hm_vs_m3_1B', 'm1m2_1B', 'c15_1B', 'c14_1B', 'c5_1B', 'c16_1B', 'c17_1B', 'recall6_1B_with_c11c12'), '2B': ('recall6_2B', 'ssd_hm_vs_m3_2B', 'm1m2_2B', 'c14_2B', 'c15_2B', 'c5_2B', 'c16_2B', 'c17_2B'), '10B': ('recall6_10B', 'c7_vs_m3_10B', 'c6_vs_m3_10B', 'c16_10B')}
ARM_ORDER = ('C1', 'C2', 'C3', 'C4', 'C5', 'C6', 'C7', 'C9', 'C12', 'C13', 'C14', 'C15', 'C16', 'C17')
MISSING = {'1B': {}, '2B': {}, '10B': {}}
ZS = (('lambada_openai', 'LAMBADA'), ('hellaswag', 'HellaSwag'), ('piqa_parquet', 'PIQA'), ('arc_easy', 'ARC-E'), ('arc_challenge', 'ARC-C'), ('winogrande', 'WinoGrande'), ('openbookqa', 'OBQA'))
R3 = (('swde', 'SWDE'), ('fda', 'FDA'), ('squad_completion', 'SQuAD'))
R6X = (('based_triviaqa', 'TriviaQA'), ('based_nq_1024', 'NQ-1024'), ('based_drop', 'DROP'))
NIAH = tuple(((f'{v}@{n}', f'{v}@{n}') for n in (512, 1024, 2048) for v in ('single_1', 'single_2', 'single_3', 'multikey_1')))
DASH = '—'
_BAD = re.compile('^\\s*([-+*>#|]|\\d+[.)])(\\s|$)')

def para(text: str, first: str='', width: int=120) -> list:
    rest = ' ' * len(first)
    for w in range(width, 80, -1):
        lines = textwrap.fill(text, width=w, initial_indent=first, subsequent_indent=rest, break_long_words=False, break_on_hyphens=False).split('\n')
        if not any((_BAD.match(ln[len(rest):]) for ln in lines[1:])):
            return lines
    raise ValueError(text)

def _row(line: str) -> list:
    return [c.strip() for c in line.strip().strip('|').split('|')]

def parse(path: Path) -> dict:
    lines = path.read_text().splitlines()
    title = lines[0]
    milestone = re.search('\\((\\d+B);', title).group(1)
    tables, cur = ([], None)
    other = []
    for ln in lines[1:]:
        if ln.startswith('|'):
            if cur is None:
                cur = []
                tables.append(cur)
            cur.append(_row(ln))
        else:
            cur = None
            if ln.strip():
                other.append(ln.strip())
    scores, paired = tables
    head = scores[0]
    rows = {r[0]: dict(zip(head[1:], r[1:])) for r in scores[2:]}
    chance = next((o for o in other if o.startswith('Within 2 SE')))
    footer = next((o for o in other if o.startswith('Points')))
    return {'dir': path.parent.name, 'title': title.lstrip('# ').strip(), 'milestone': milestone, 'scores': rows, 'arms': [r[0] for r in scores[2:]], 'paired': paired, 'chance': chance, 'footer': footer}

def load(repo: Path=REPO) -> dict:
    return {d: parse(repo / RAW / d / 'table.md') for ds in DIRS.values() for d in ds}

def mean(vals) -> str:
    q = sum((Fraction(Decimal(v)) for v in vals)) / len(vals)
    return str((Decimal(q.numerator) / Decimal(q.denominator)).quantize(Decimal('0.1'), rounding=ROUND_HALF_UP))

def merged(raw: dict, milestone: str):
    out, checked, bad = ({}, 0, [])
    for d in DIRS[milestone]:
        t = raw[d]
        assert t['milestone'] == milestone, (d, t['milestone'])
        for arm, row in t['scores'].items():
            dst = out.setdefault(arm, {})
            for task, v in row.items():
                task = task.replace('niah:', '')
                if task in dst:
                    checked += 1
                    if dst[task][0] != v:
                        bad.append(f'{arm} {task}: {dst[task][0]} (`{dst[task][1]}`) vs {v} (`{d}`)')
                else:
                    dst[task] = (v, d)
    return (out, checked, bad)

def _table(head, rows) -> list:
    return ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)] + ['| ' + ' | '.join(r) + ' |' for r in rows]

def _arms(data: dict, milestone: str) -> list:
    arms = set(data) | set(MISSING[milestone])
    return [a for a in ARM_ORDER if a in arms] + sorted(arms - set(ARM_ORDER))

def _src(data, arms, keys) -> str:
    ds = []
    for a in arms:
        for k, _ in keys:
            if a in data and k in data[a] and (data[a][k][1] not in ds):
                ds.append(data[a][k][1])
    return ', '.join((f'`{RAW}/{d}/table.md`' for d in ds))
MEASURES = {'ZS': ZS, 'Recall-3': R3, 'Recall-6': R3 + R6X, 'NIAH': NIAH}

def check_7b(raw: dict, text: str) -> list:
    lines = text.splitlines()
    i = next((k for k, ln in enumerate(lines) if ln.startswith('| arm | ZS 1B')))
    head = _row(lines[i])
    data = {ms: merged(raw, ms)[0] for ms in DIRS}
    n, diff, noraw = (0, [], [])
    for ln in lines[i + 2:]:
        if not ln.startswith('|'):
            break
        r = _row(ln)
        for h, cell in zip(head[1:], r[1:]):
            v = cell.replace('*', '').split(' ')[0]
            meas, ms = h.rsplit(' ', 1)
            if r[0] not in data[ms]:
                if v != DASH:
                    noraw.append(f'{r[0]} {h} = {v}')
                continue
            vals = [data[ms][r[0]][k][0] for k, _ in MEASURES[meas]]
            n += 1
            exact = sum((Fraction(Decimal(x)) for x in vals)) / len(vals)
            if mean(vals) != v:
                diff.append(f'{r[0]} {h}: implementationb {v}, computed {mean(vals)} (mean of the shown per-task values {float(exact):.3f})')
    o = [f'**Check of the implementationb means against the raw tables (generated).** {n} means of the implementationb table have per-task scores in the raw tables; {n - len(diff)} equal the mean computed here.']
    if diff:
        o[0] += f' {len(diff)} differ by 0.1, each where the mean of the shown values ends in 5 at the second decimal (a rounding direction; for NIAH, whose cells are whole items out of 100, an exact tie). They are reported, **not changed in implementationb**:'
    o = para(o[0]) + [''] + [ln for d in diff for ln in para(d, '- ')]
    if noraw:
        o += [''] + para('implementationb means with no per-task scores in the repo (no raw table.md): ' + '; '.join(noraw) + '.')
    return o + ['']

def section_7c(raw: dict, text: str) -> list:
    o = ['### 7c. Per-task downstream scores (all arms, every milestone)', '']
    o += para('Points (percent), one seed per arm, protocol in implementation. Every per-task cell is copied from the raw evaluator table named under it (when an arm is in several raw tables, from the first one listed; the cross-table check below compares the rest). The means are **computed here** from the rounded per-task values in the same row (arithmetic mean, rounded half-up to 0.1), because the raw tables carry no per-arm means. Recall-6 is the recall measure; Recall-3 = SWDE/FDA/SQuAD. NIAH is RULER-style (our reimplementation of the RULER templates, 100 items per cell). `—` = not evaluated or not in the repo; the reason is under the table. The withdrawn RULER multi-needle probe (implementationb) is not included.') + ['']
    for ms in DIRS:
        data, checked, bad = merged(raw, ms)
        arms = _arms(data, ms)
        missing = [ln for a, r in MISSING[ms].items() for ln in para(f'{a} ({DASH}): {r}', '- ')]
        o += [f'#### 7c, {ms}', '']
        rows = []
        for a in arms:
            if a in MISSING[ms]:
                rows.append([a] + [DASH] * (len(ZS) + 1))
                continue
            v = [data[a][k][0] for k, _ in ZS]
            rows.append([a] + v + [mean(v)])
        o += [f'**Zero-shot, {ms}**', ''] + _table(['arm'] + [n for _, n in ZS] + ['ZS mean'], rows)
        o += [''] + para(f'Source: {_src(data, arms, ZS)}.') + missing + ['']
        rows, notes = ([], [])
        has6 = any((k in data[a] for a in data for k, _ in R6X))
        for a in arms:
            if a in MISSING[ms]:
                rows.append([a] + [DASH] * (len(R3) + len(R6X) + 2))
                continue
            v3 = [data[a][k][0] for k, _ in R3]
            if all((k in data[a] for k, _ in R6X)):
                v6 = [data[a][k][0] for k, _ in R6X]
                rows.append([a] + v3 + v6 + [mean(v3), mean(v3 + v6)])
            else:
                rows.append([a] + v3 + [DASH] * len(R6X) + [mean(v3), DASH])
        if not has6:
            notes = para(f'TriviaQA / NQ-1024 / DROP and Recall-6 ({DASH}): the six-task recall was not run at {ms} (run at 2B and 10B only, the `recall6_*` tables).', '- ')
        o += [f'**Recall, {ms}** (Recall-6 is the recall measure)', '']
        o += _table(['arm'] + [n for _, n in R3 + R6X] + ['Recall-3 mean', 'Recall-6 mean'], rows)
        o += [''] + para(f'Source: {_src(data, arms, R3 + R6X)}.') + notes + missing + ['']
        rows = []
        for a in arms:
            if a in MISSING[ms]:
                rows.append([a] + [DASH] * (len(NIAH) + 1))
                continue
            v = [data[a][k][0] for k, _ in NIAH]
            rows.append([a] + v + [mean(v)])
        o += [f'**NIAH, {ms}**: RULER-style (our implementation) single_1–3 + multikey_1 at 512 / 1024 / 2048 tokens', '']
        o += _table(['arm'] + [n for _, n in NIAH] + ['NIAH mean'], rows)
        o += [''] + para(f'Source: {_src(data, arms, NIAH)}.') + missing
        o += para('Every NIAH cell uses the 2026-10-06 stop rule: skip a leading ":"/whitespace prefix, then stop at the first newline (note (c) of implementationb).', '- ')
        o.append('')
        n_tab = len(DIRS[ms])
        if bad:
            o += para(f'Cross-table check, {ms}: {checked} overlapping cells in the {n_tab} raw tables, {len(bad)} disagree:') + [ln for b in bad for ln in para(b, '- ')] + ['']
        else:
            o += para(f'Cross-table check, {ms}: {checked} cells of arms listed in more than one of the {n_tab} raw tables compared; all agree.') + ['']
    return o + check_7b(raw, text)

def _family(t: dict) -> str:
    return ', '.join(t['paired'][0][1:])

def section_7d(raw: dict) -> list:
    o = ['### 7d. Paired comparisons (every raw table, verbatim)', '']
    o += para('Difference in points [95% CI] from the paired item bootstrap (B = 20,000, seed 11); `*` = Holm-adjusted p < 0.05, where the Holm family is the set of comparisons in that table for one measure, so stars can differ between tables that share a comparison. Intervals cover evaluation items only, not seeds. In the `recall6_*` tables "recall mean" is Recall-6 and "recall3 mean" is Recall-3; in every other table "recall mean" is Recall-3 (SWDE/FDA/SQuAD). NIAH rows are RULER-style (our implementation). Rows and cells are copied unchanged from the raw file cited under each table.') + ['']
    k = 0
    for ms, ds in DIRS.items():
        for d in ds:
            t = raw[d]
            k += 1
            o += [f'#### 7d.{k} {ms}: `{d}`', '']
            o += para(f"Arms {', '.join(t['arms'])}. Holm family (per measure): {_family(t)}.") + ['']
            o += ['| ' + ' | '.join(r) + ' |' if i != 1 else '|' + '---|' * len(r) for i, r in enumerate(t['paired'])]
            o += [''] + para(f"Source: `{RAW}/{d}/table.md` ({t['title']}). {t['chance']}.") + ['']
    return o

def generate(repo: Path=REPO) -> str:
    raw = load(repo)
    text = (repo / TASK).read_text()
    return '\n'.join([BEGIN] + section_7c(raw, text) + section_7d(raw) + [END]) + '\n'

def embedded(text: str) -> str:
    i, j = (text.index(BEGIN), text.index(END))
    return text[i:j + len(END)] + '\n'

def main():
    p = argparse.ArgumentParser()
    p.add_argument('--write', action='store_true', help=f'replace the marked block in {TASK}')
    a = p.parse_args()
    out = generate()
    if not a.write:
        sys.stdout.write(out)
        return
    path = REPO / TASK
    text = path.read_text()
    old = embedded(text)
    path.write_text(text.replace(old, out, 1))
    print(f'wrote {TASK}')
if __name__ == '__main__':
    main()
