
from pathlib import Path
import hashlib, json, math
from hm_campaign_views import HMCampaign
B = Path(__file__).resolve().parents[1] / 'tables' / 'bench'
hm = HMCampaign(B / 'hm_optimization.json')
LEDGER = {'hm_optimization.json': hashlib.sha256((B / 'hm_optimization.json').read_bytes()).hexdigest()}

def rows(name):
    p = B / name
    LEDGER[name] = hashlib.sha256(p.read_bytes()).hexdigest()
    data = [[c.strip() for c in l.removesuffix('\\\\').strip().split('&')] for l in p.read_text().splitlines() if '&' in l and l.rstrip().endswith('\\\\')][1:]
    return hm.overlay_rows(name, data)

def marks(s):
    return s.replace(' (noise gate)', '').replace('$^\\ddagger$', '\\textsuperscript{a}').replace('$^\\S$', '\\textsuperscript{b}').replace('$^\\ast$', '\\textsuperscript{c}')

def output(name, header, data):
    text = '% Generated by paper/figures/bench_tables.py from accepted fragments.\n'
    text += '\\begin{tabular}{@{}l' + 'r' * (len(header) - 1) + '@{}}' + '\n\\toprule\n'
    text += ' & '.join(header) + ' \\\\' + '\n\\midrule\n'
    text += '\n'.join((' & '.join((marks(c) for c in r)) + ' \\\\' for r in data))
    text += '\n\\bottomrule\n\\end{tabular}\n'
    (B / name).write_text(text)

def pair(name, left, right):
    a, b = (rows(left), rows(right))
    assert [r[0] for r in a] == [r[0] for r in b]
    output(name, ['Model', 'Balanced', 'Long', 'Wide', 'Batch', 'LM'], [[x[0]] + [u if u == v and u.startswith('n/a') else u + ' / ' + v for u, v in zip(x[1:], y[1:])] for x, y in zip(a, b)])
pair('compact_inference.tex', 'app_scope_fwd_ms.tex', 'app_mixer_fwd_ms.tex')
pair('compact_training.tex', 'app_mixer_eager_fb_ms.tex', 'app_mixer_graph_fb_ms.tex')
pair('compact_scope_memory.tex', 'app_saved_scope_mib.tex', 'app_peak_scope_mib.tex')
pair('compact_mixer_memory.tex', 'app_saved_mixer_mib.tex', 'app_peak_mixer_mib.tex')
data = []
small = []
for name, key in [('Mamba 1', '1a_m1'), ('Mamba 2', '1b_m2'), ('Mamba 3 SISO', '1c_m3')]:
    for r in rows('table' + key + '.tex'):
        data.append([name + ' / ' + r[0]] + [r[i] for i in [1, 2, 3, 4, 5, 6]])
    for r in rows('table' + key + '_rest.tex'):
        small.append([name + ' / ' + r[0]] + r[1:])
output('compact_recovery_extras.tex', ['Baseline / set', 'Kernel fwd', 'Kernel f+b', 'Mixer eager f+b', 'Mixer graph f+b', 'Extra saved', 'Peak'], data)
output('compact_small_summary.tex', ['Baseline / set', 'Kernel fwd', 'Kernel f+b', 'Mixer eager f+b', 'Mixer graph f+b', 'Extra saved', 'Peak'], small)
output('table1a_m1_current_detail.tex', ['Shape', 'Kernel fwd', 'Kernel f+b', 'Mixer eager f+b', 'Mixer graph f+b'], hm.detail(rows('table1a_m1_detail.tex')))
source = B / 'five_shape_recovery.json'
LEDGER[source.name] = hashlib.sha256(source.read_bytes()).hexdigest()
recovery = hm.recovery(json.loads(source.read_text()))
(B / 'five_shape_recovery_current.json').write_text(json.dumps(recovery, indent=2) + '\n')
memory_source = B / 'retained_memory.json'
LEDGER[memory_source.name] = hashlib.sha256(memory_source.read_bytes()).hexdigest()
memory = json.loads(memory_source.read_text())
hm.validate_retained(memory)
arms = {'1a_m1': ('HMM:m1exact', 'official_m1', 'official_mamba1'), '1b_m2': ('PM:m2exact', 'official_m2', 'official_mamba2'), '1c_m3': ('PM:m3exact', 'official_m3_siso', 'official_mamba3')}
retained = {}
for scope in ('kernel', 'mixer'):
    records = memory['table3_' + scope]
    assert len(records) == 30
    index = {(r['arm'], r['shape_tag']): r for r in records}
    assert len(index) == len(records)
    for key, (ours, kernel, mixer) in arms.items():
        for shape in recovery['shapes']:
            memory_shape = 'lm' if shape == 'lm_b6_d2048_l2048' else shape
            a, b = (index[arm, memory_shape] for arm in (ours, kernel if scope == 'kernel' else mixer))
            for dim in ('B', 'L', 'd_inner', 'N'):
                assert a['geometry'][dim] == b['geometry'][dim]
            assert a['geometry']['N'] == (16 if key == '1a_m1' else 128)
            retained[key, scope, shape] = a['total_retained_nonparameter_bytes'] / b['total_retained_nonparameter_bytes']
keys = ['1a_m1', '1b_m2', '1c_m3']
lines = ['% Generated by paper/figures/bench_tables.py; accepted ratios; HM pair refreshed from the validated campaign.', '\\begin{tabular}{@{}lrrrrrr@{}}', '\\toprule', '& \\multicolumn{2}{c}{HM / Mamba 1} & \\multicolumn{2}{c}{SSD / Mamba 2} & \\multicolumn{2}{c}{SSD / Mamba 3 SISO} \\\\', '\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(l){6-7}', 'Shape & Kernel & Mixer & Kernel & Mixer & Kernel & Mixer \\\\']
for title, scopes, unit in [('Forward-and-backward time', ['kernel', 'mixer'], 'ms'), ('Peak memory', ['kernel_peak', 'mixer_peak'], 'bytes'), ('Retained for backward', ['kernel_retained', 'mixer_retained'], 'bytes')]:
    lines += ['\\midrule', '\\multicolumn{7}{l}{\\emph{' + title + ' ratios}} \\\\', '\\addlinespace[2pt]']
    for j, shape in enumerate(['Balanced', 'Long', 'Wide', 'Batch', 'LM']):
        vals = []
        for k in keys:
            cell = recovery['pairs'][k]['cells'][j]
            assert cell['shape'] == recovery['shapes'][j]
            for scope in scopes:
                if scope.endswith('_retained'):
                    vals.append(f"{retained[k, scope.removesuffix('_retained'), cell['shape']]:.2f}")
                    continue
                v = cell[scope]
                assert v['ratio'] == v['ours_' + unit] / v['official_' + unit]
                vals.append(f"{v['ratio']:.2f}")
        lines.append(' & '.join([shape] + vals) + ' \\\\')
    means = [math.exp(sum((math.log(retained[k, scope.removesuffix('_retained'), c['shape']] if scope.endswith('_retained') else c[scope]['ratio']) for c in recovery['pairs'][k]['cells'])) / 5) for k in keys for scope in scopes]
    lines.append('\\addlinespace[2pt]')
    lines.append(' & '.join(['Geomean (5 shapes)'] + [f'{v:.2f}' for v in means]) + ' \\\\')
lines += ['\\bottomrule', '\\end{tabular}']
(B / 'table3_parity_shapes.tex').write_text('\n'.join(lines) + '\n')
cost = {r[0]: r for r in rows('table2_main_kernel_fb_ms.tex')}
