(B / 'table4_cost_readable.tex').write_text('\n'.join(lines) + '\n')
tradeoff = []
for width in (64, 32):
    for percent in (0, 75, 100):
        arm = f'HM-{percent}' + ('@P32' if width == 32 else '')
        ratios = []
        for role in ('cost_kernel', 'cost_mixer'):
            v = [hm.timing(role, arm, shape, 128)['ratio'] for shape in hm.shapes]
            ratios.append(math.exp(sum(map(math.log, v)) / len(v)))
        for level in ('scope', 'mixer'):
            v = [hm.mem(level, arm, shape, 128)['peak_ratio'] for shape in hm.shapes]
            ratios.append(math.exp(sum(map(math.log, v)) / len(v)))
        tradeoff.append([f'HM-{percent}, P={width}'] + [f'{v:.3f}' for v in ratios])
