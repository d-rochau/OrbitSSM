lines = ['% Generated by paper/figures/bench_tables.py; accepted absolute values; HM/Mamba 1 refreshed from the validated campaign.', '\\begin{tabular}{@{}lrrrrrr@{\\hspace{1.2em}}r@{}}', '\\toprule', '& \\multicolumn{4}{c}{Kernel time (ms)} & \\multicolumn{3}{c}{LM (one shape)} \\\\', '\\cmidrule(lr){2-5}\\cmidrule(l){6-8}', 'Model & Balanced & Long & Wide & Batch & Time & Retained & Peak \\\\', '& & & & & (ms) & (MiB) & (MiB) \\\\', '\\midrule']
