
from __future__ import annotations
import argparse, json
from pathlib import Path
ARMS = [('official_mamba3_mimo', 'Mamba-3 MIMO'), ('official_mamba3', 'Mamba-3 SISO'), ('official_mamba2', 'Mamba-2'), ('official_mamba1', 'Mamba-1'), ('llama3_attention', 'Llama-3 attention')]
MILESTONES = [('10B', '_d10B')]
TASKS = [('lambada_openai', 'LAMBADA'), ('hellaswag', 'HellaSwag'), ('piqa_parquet', 'PIQA'), ('arc_easy', 'ARC-E'), ('arc_challenge', 'ARC-C'), ('winogrande', 'WinoG.'), ('openbookqa', 'OBQA')]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--runs-dir', default='./local-data')
    ap.add_argument('--out', default=str(Path(__file__).resolve().parents[3] / 'paper' / 'tables' / 'lm_fineweb_zeroshot.tex'))
    a = ap.parse_args()
    rows = []
    for arm, label in ARMS:
        for ms, suffix in MILESTONES:
            f = Path(a.runs_dir) / f'lmc_{arm}_seed0{suffix}' / f'lmeval_zeroshot_{ms}.json'
            if not f.exists():
                continue
            res = next(iter(json.load(open(f)).values()))
            cells = []
            for t, _ in TASKS:
                v = res.get(t, {}).get('value')
                cells.append(f'{100 * v:.1f}' if v is not None else '--')
            mean = res.get('_mean')
            rows.append(f'{label} & {ms} & ' + ' & '.join(cells) + f' & {100 * mean:.1f} \\\\' if mean is not None else '')
            print(f'{label:20s} {ms:>3s}  ' + '  '.join(cells) + f'  mean {100 * mean:.1f}')
    head = "% paper/tables/lm_fineweb_zeroshot.tex -- GENERATED by experiments/lm/tools/lm_zeroshot_table.py\n% Zero-shot accuracy (%) via lm-eval-harness on the preserved milestone checkpoints (acc_norm where defined, else acc);\n% the Mamba-3 paper's App.-D suite. Secondary to the test-shard loss: at this scale most tasks sit near chance and\n% move by 1-2 points between seeds, so they do not rank arms that are 0.003 nats apart.\n\\begin{tabular}{llrrrrrrrr}\n\\toprule\nmodel & tokens & " + ' & '.join((n for _, n in TASKS)) + ' & mean \\\\\n\\midrule\n'
    Path(a.out).write_text(head + '\n'.join((r for r in rows if r)) + '\n\\bottomrule\n\\end{tabular}\n')
    print('wrote', a.out)
if __name__ == '__main__':
    main()
