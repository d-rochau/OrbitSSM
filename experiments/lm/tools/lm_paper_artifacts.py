
from __future__ import annotations
import argparse, json, math, os, re
from pathlib import Path
ARMS = [('official_mamba3_mimo', 'C4', 'Mamba-3 MIMO', 'lmMimo', '1baf7a'), ('official_mamba3', 'C3', 'Mamba-3 SISO', 'lmM3', '2a78d6'), ('official_mamba2', 'C2', 'Mamba-2', 'lmM2', 'eb6834'), ('official_mamba1', 'C1', 'Mamba-1', 'lmM1', 'eda100'), ('llama3_attention', 'C5', 'Llama-3 attention', 'lmAttn', 'e87ba4')]
GEOM = {'official_mamba3_mimo': (27, 2048, 504.5), 'official_mamba3': (29, 2048, 507.9), 'official_mamba2': (29, 2048, 505.2), 'official_mamba1': (28, 1983, 507.9), 'llama3_attention': (29, 2861, 507.9)}

def read_curve(run: Path, max_tokens: int):
    pts = {}
    for line in open(run / 'metrics.jsonl'):
        try:
            j = json.loads(line)
        except json.JSONDecodeError:
            continue
        if 'val_loss' in j and j['tokens'] <= max_tokens:
            pts[j['tokens']] = j['val_loss']
    return sorted(pts.items())

def read_milestone(run: Path, tag: str):
    f = run / f'milestone_eval_{tag}.txt'
    if not f.exists():
        return None
    last = [l for l in open(f) if l.strip()][-1].split()
    return (float(last[-2]), float(last[-1]))

def read_tok_s(run: Path):
    v = [json.loads(l)['tok_s'] for l in open(run / 'metrics.jsonl') if '"tok_s"' in l]
    v = v[-50:]
    return sum(v) / len(v) if v else float('nan')
CONT_SUFFIX = '_d10B'

def read_cont_curve(runs: Path, arm: str):
    d = runs / f'lmc_{arm}_seed0{CONT_SUFFIX}'
    if not (d / 'metrics.jsonl').exists():
        return []
    return [(t, v) for t, v in read_curve(d, 10500000000) if t >= 2000000000]

def tikz_figure(curves, out: Path, cont=None):

    def panel(x0, x1, y0, y1, w, h, xt, yt, title, label_end):
        sx = lambda x: w * (x - x0) / (x1 - x0)
        sy = lambda y: h * (y - y0) / (y1 - y0)
        L = [f'  % ---- {title}']
        for y in yt:
            L.append(f'  \\draw[black!12] (0,{sy(y):.3f}) -- ({w},{sy(y):.3f});')
        L.append(f'  \\draw[black!65] (0,0) rectangle ({w},{h});')
        for x in xt:
            L.append(f'  \\node[below, font=\\scriptsize] at ({sx(x):.3f},0) {{{x:g}}};')
        for y in yt:
            L.append(f'  \\node[left, font=\\scriptsize] at (0,{sy(y):.3f}) {{{y:.1f}}};')
        L.append(f'  \\node[below=3.5mm, font=\\scriptsize] at ({w / 2},0) {{tokens (B)}};')
        L.append(f'  \\node[above, font=\\scriptsize] at ({w / 2},{h}) {{{title}}};')
        for arm, cid, lab, col, _ in ARMS:
            pts = [(t / 1000000000.0, v) for t, v in curves[arm] if x0 <= t / 1000000000.0 <= x1 and y0 <= v <= y1]
            if not pts:
                continue
            path = ' -- '.join((f'({sx(x):.3f},{sy(y):.3f})' for x, y in pts))
            L.append(f'  \\draw[line width=0.9pt, {col}] {path};')
            if label_end:
                x, y = pts[-1]
                L.append(f'  \\node[right, font=\\tiny, text=black!80] at ({sx(x):.3f},{sy(y):.3f}) {{{lab}}};')
        return '\n'.join(L)
    left = panel(0.1, 2.0, 3.0, 5.4, 3.6, 3.2, [0.5, 1.0, 1.5, 2.0], [3.0, 3.5, 4.0, 4.5, 5.0], 'validation loss, 0.1--2B', False)
    right = panel(1.0, 2.0, 3.0, 3.45, 3.6, 3.2, [1.0, 1.5, 2.0], [3.0, 3.1, 3.2, 3.3, 3.4], 'zoom, 1--2B', True)
    third = ''
    if cont and any(cont.values()):
        saved = dict(curves)
        for arm in curves:
            curves[arm] = cont.get(arm, [])
        third = panel(2.0, 10.0, 2.6, 3.1, 3.6, 3.2, [2, 4, 6, 8, 10], [2.6, 2.7, 2.8, 2.9, 3.0], 'continuation, 2--10B (cosine decay)', True)
        curves.update(saved)
    colors = '\n'.join((f'\\definecolor{{{col}}}{{HTML}}{{{hx}}}' for _, _, _, col, hx in ARMS))
    leg = []
    for i, (_, _, lab, col, _) in enumerate(ARMS):
        x, y = (i % 3 * 3.5, -1.05 - i // 3 * 0.45)
        leg.append(f'  \\draw[line width=0.9pt, {col}] ({x:.2f},{y:.2f}) -- ({x + 0.45:.2f},{y:.2f});')
        leg.append(f'  \\node[right, font=\\scriptsize, inner sep=1pt] at ({x + 0.45:.2f},{y:.2f}) {{{lab}}};')
    legend = '\n'.join(leg)
    src = f'% paper/figures/lm_fineweb_curves.tex -- GENERATED by experiments/lm/tools/lm_paper_artifacts.py\n% from runs/lmc_<arm>_seed0/metrics.jsonl (validation every 100M tokens, held-out validation shard).\n% Recipe: implementationtasks/TASK_P1_LLM_20260914.md (500M class, seed 0). Do not edit by hand; rerun the script.\n{colors}\n\\begin{{tikzpicture}}[x=1cm, y=1cm, font=\\footnotesize]\n{left}\n\\begin{{scope}}[xshift=4.9cm]\n{right}\n\\end{{scope}}\n\\begin{{scope}}[xshift=9.8cm]\n{third}\n\\end{{scope}}\n  % ---- legend\n{legend}\n\\end{{tikzpicture}}\n'
    out.write_text(src)

def booktabs_table(rows, out: Path):
    head = '% paper/tables/lm_fineweb_milestones.tex -- GENERATED by experiments/lm/tools/lm_paper_artifacts.py\n% Test-shard loss / perplexity at the preserved 1B, 2B and (where continued) 10B milestone checkpoints (200 batches x 6 x 2048 tokens);\n% the 10B column is the declared cosine-decay continuation from the 2B checkpoint (compiled), "--" = not continued.\n% implementationtasks/TASK_P1_LLM_20260914.md configs C1-C5, seed 0. Rows for our arms are appended by the same script.\n\\begin{tabular}{llrrrcccr}\n\\toprule\nmodel & config & layers & $d_{\\mathrm{int}}$ & params (M) & 1B test loss / ppl & 2B test loss / ppl & 10B test loss / ppl & tok/s \\\\\n\\midrule\n'
    body = '\n'.join(rows) + '\n'
    out.write_text(head + body + '\\bottomrule' + '\n' + '\\end{tabular}' + '\n')

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--runs-dir', default='./local-data')
    ap.add_argument('--out-dir', default=str(Path(__file__).resolve().parents[3] / 'paper'))
    a = ap.parse_args()
    runs, out = (Path(a.runs_dir), Path(a.out_dir))
    curves, rows, cont = ({}, [], {})
    for arm, cid, lab, col, _ in ARMS:
        run = runs / f'lmc_{arm}_seed0'
        curves[arm] = read_curve(run, 2000500000)
        m1, m2 = (read_milestone(run, '1B'), read_milestone(run, '2B'))
        m10 = read_milestone(runs / f'lmc_{arm}_seed0{CONT_SUFFIX}', '10B')
        cont[arm] = read_cont_curve(runs, arm)
        L, di, P = GEOM[arm]
        f = lambda m: f'{m[0]:.4f} / {m[1]:.2f}' if m else '--'
        rows.append(f'{lab} & {cid} & {L} & {di} & {P:.1f} & {f(m1)} & {f(m2)} & {f(m10)} & {read_tok_s(run) / 1000.0:.0f}k \\\\')
        print(f'{lab:20s} {len(curves[arm]):2d} val points  1B={m1}  2B={m2}')
    (out / 'figures').mkdir(exist_ok=True)
    (out / 'tables').mkdir(exist_ok=True)
    tikz_figure(curves, out / 'figures' / 'lm_fineweb_curves.tex', cont)
    booktabs_table(rows, out / 'tables' / 'lm_fineweb_milestones.tex')
    print('wrote', out / 'figures' / 'lm_fineweb_curves.tex', 'and', out / 'tables' / 'lm_fineweb_milestones.tex')
if __name__ == '__main__':
    main()
